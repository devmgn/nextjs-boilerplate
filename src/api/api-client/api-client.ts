/**
 * Error representing a non-2xx response or a response that cannot be read as
 * JSON.
 */
export class ApiError extends Error {
  readonly status: number;
  /**
   * Raw text of the response body. Not parsed, because the error format differs
   * per API.
   */
  readonly body: string;

  /**
   * @param response - The failed response. Used to derive the status and
   *   message
   * @param body - Raw text of the response body
   * @param message - Error message. Derived from the status when omitted
   */
  constructor(response: Response, body: string, message?: string) {
    super(
      message ?? `API request failed: ${response.status} ${response.statusText}`
    );
    this.name = "ApiError";
    this.status = response.status;
    this.body = body;
  }
}

/**
 * Determines whether a value is an `ApiError`. If multiple `ApiError` classes
 * are loaded (e.g. due to bundle duplication), `instanceof` returns false, so a
 * structural check on `name` and `status` is also used.
 *
 * @param error - The value to check
 * @returns `true` if `error` can be treated as an `ApiError`
 */
export function isApiError(error: unknown): error is ApiError {
  if (error instanceof ApiError) {
    return true;
  }

  if (!(error instanceof Error) || error.name !== "ApiError") {
    return false;
  }

  return (
    "status" in error &&
    typeof error.status === "number" &&
    "body" in error &&
    typeof error.body === "string"
  );
}

/** Used as `TError` for the queries / mutations generated by Orval. */
export type ErrorType<_Error> = ApiError;

/**
 * Reads the body of an error response. If reading fails midway, falls back to
 * an empty string so the result is still an ApiError with a status.
 *
 * @param response - The failed response
 * @returns The body text, or an empty string if reading fails
 */
async function readErrorBody(response: Response): Promise<string> {
  try {
    return await response.text();
  } catch {
    return "";
  }
}

const NO_CONTENT_STATUSES = new Set([204, 205]);

/**
 * Mutator for the API functions generated by Orval. To surface failures in
 * TanStack Query's error state, throws `ApiError` for non-2xx responses and
 * responses that cannot be read as JSON; on success, returns only the body.
 *
 * @typeParam T - The response body (generated from the OpenAPI spec)
 * @param url - The request URL
 * @param init - Request options passed to `fetch`
 * @returns The response body parsed as JSON, or `undefined` for a successful
 *   response without a body
 */
export async function apiClient<T>(
  url: string,
  init?: RequestInit
): Promise<T> {
  const response = await fetch(url, init);

  if (!response.ok) {
    throw new ApiError(response, await readErrorBody(response));
  }

  const text = await response.text();

  // T is the response type generated from the OpenAPI spec. To avoid the cost of runtime validation, the spec is trusted as the contract and not validated.
  if (NO_CONTENT_STATUSES.has(response.status) || text === "") {
    // SAFETY: Successful responses without a body are limited to operations that are void in the spec (e.g. delete).
    // oxlint-disable-next-line typescript/no-unsafe-type-assertion
    return undefined as T;
  }

  try {
    // SAFETY: The response shape trusts the spec (= T) as the contract.
    // oxlint-disable-next-line typescript/no-unsafe-type-assertion
    return JSON.parse(text) as T;
  } catch {
    throw new ApiError(response, text, "API response is not valid JSON");
  }
}
